// Realistic mock data for the User Management demo. Login times are generated
// relative to "today" so the Today/Yesterday formatting stays meaningful.

const now = new Date();

function loginAt(daysAgo, hour, minute) {
  const d = new Date(now);
  d.setDate(d.getDate() - daysAgo);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

